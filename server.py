def log_pdu(direction: str, peer_label: str, pdu: dict):
    """Print a clearly-labelled, readable line for every PDU when verbose mode is on.
    direction: 'SEND' or 'RECV'
    peer_label: human-readable identifier for the other end (e.g. 'player_1' or address tuple)
    """
    if not VERBOSE:
        return
    timestamp = datetime.datetime.now().strftime("%H:%M:%S.%f")[:-3]
    label = f"S->{peer_label}" if direction == "SEND" else f"{peer_label}->S"
    print(f"[VERBOSE {timestamp}] [{label}] {json.dumps(pdu)}")

# global game_phase
game_phase = "LOBBY"
# server seq num
server_seq_num = 0

# --- turn / priority state (populated once IN_GAME begins, see begin_turn()) ---
turn_number = 0
current_step = None      # e.g. "UPKEEP", "DRAW", "PRECOMBAT_MAIN", ...
active_conn = None        # connection of the Active Player (AP) this turn
priority_conn = None       # connection that currently holds priority
priority_seq_num = None    # seq_num the priority holder must echo in PRIORITY_PASS
consecutive_passes = 0     # how many players have passed in a row in this window
