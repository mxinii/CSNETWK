def show_cards(title, card_ids):
    """Print card names and exact protocol IDs for convenient copy/typing."""
    print(f"\n{title} ({len(card_ids)}):")
    if not card_ids:
        print("  (none)")
        return
    for card_id in card_ids:
        info = cards.get(card_id, {})
        cost = info.get("cost", {})
        generic = int(cost.get("Generic") or 0)
        mana_cost = (f"{{{generic}}}" if generic else "") + "".join(
            f"{{{color}}}" * int(cost.get(color) or 0) for color in "WUBRG")
        cost_text = f" cost={mana_cost or '{0}'}" if info.get("card_type") != "Land" else ""
        print(f"  {card_id} — {info.get('card_name', 'Unknown')} "
              f"[{info.get('card_type', 'Unknown')}]{cost_text}")

def known_target_ids(state):
    """Targets visible to this client: players, battlefield objects, and stack items."""
    result = list(state.get("life_totals", {}))
    result.extend(perm.get("id") for permanents in state.get("battlefield", {}).values()
                  for perm in permanents if perm.get("id"))
    result.extend(item.get("stack_item_id") for item in state.get("stack", [])
                  if item.get("stack_item_id"))
    return result

def visible_mana(state, owner_id):
    pool = state.get("mana_pool", {})
    untapped_lands = [perm.get("id") for perm in state.get("battlefield", {}).get(owner_id, [])
                      if not perm.get("tapped")
                      and cards.get(perm.get("id"), {}).get("card_type") == "Land"]
    pool_text = ", ".join(f"{color}:{amount}" for color, amount in pool.items() if amount) or "empty"
    return pool_text, untapped_lands

def send_pdu(sock, pdu: dict):
    log_pdu("SEND", pdu)
    with send_lock:
        sock.sendall(encode_pdu(pdu))

def recv_exact(sock, n):
    data = b""
    while len(data) < n:
        chunk = sock.recv(n - len(data))
        if not chunk:
            return None
        data += chunk
    return data

def recv_pdu(sock):
    pdu = wire_recv_pdu(sock)
    if pdu is None: return None
    log_pdu("RECV", pdu)
    return pdu

