def register_player(sock, input_fn=input, output_fn=print):
    """Register a non-empty, lobby-unique player name.

    The server owns the lobby, so only it can determine whether another client
    already uses a name.  A duplicate response therefore keeps this connection
    open and asks the joining player for a replacement name.
    """
    while True:
        player_name = prompt_until(
            "Enter player name: ",
            lambda value: nonempty(value, "player name", 64),
            input_fn=input_fn,
            output_fn=output_fn,
        )
        send_pdu(sock, {
            "type": "PLAYER_READY",
            "seq_num": 1,
            "player_id": player_name,
            "deck_list": deck_list,
        })
        reply = recv_pdu(sock)
        if reply is None:
            return None, None
        if reply.get("type") == "ERROR" and reply.get("code") == "DUPLICATE_ID":
            output_fn("Name already taken. Please enter a different name.")
            continue
        return player_name, reply

