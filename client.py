        if untapped_lands:
            print(f"\nUntapped lands ({len(untapped_lands)}):")
            # Get your battlefield list from latest_state
            my_battlefield = latest_state.get("battlefield", {}).get(player_id, [])
            perm_dict = {p.get("id"): p for p in my_battlefield if isinstance(p, dict)}
            
            for land_id in untapped_lands:
                card_data = cards.get(land_id, {})
                perm_state = perm_dict.get(land_id, {})
                print(f"  {format_land_display(land_id, card_data, perm_state)}")
        while True:
            action = prompt_until("Action? p=pass, l=land, s=spell, x=ability, c=concede: ",
                                  lambda x: choice(x,("p","l","s","x","c"),"action"))

            if action == "c":
                send_pdu(client_socket, {"type": "CONCEDE", "seq_num": reply.get("seq_num")})
                break

            if action == "p":
                send_pdu(client_socket, {"type": "PRIORITY_PASS", "seq_num": reply.get("seq_num")})
                break

            hand = latest_state.get("hand", [])

            if action == "l":
                if latest_state.get("land_played_this_turn"):
                    print("You already played a land this turn. Choose another action.")
                    continue
                if active_player != player_id:
                    print(f"Cannot play a land now. It is {active_player}'s turn; wait for your own main phase.")
                    continue
                if step not in ("PRECOMBAT_MAIN", "POSTCOMBAT_MAIN"):
                    print(f"Cannot play a land during {step}. Wait for PRECOMBAT_MAIN or POSTCOMBAT_MAIN.")
                    continue
                legal = [cid for cid in hand if cards.get(cid, {}).get("card_type") == "Land"]
                if not legal:
                    print("No land in your hand. Choose another action.")
                    continue
                show_cards("Lands you can play", legal)
                land_id = prompt_until("Land card ID: ",
                    lambda x: nonempty(x,"land ID") if x.strip() in legal else (_ for _ in ()).throw(ValueError("choose a Land from your displayed hand")))
                send_pdu(client_socket, {"type":"PLAY_LAND", "seq_num":reply["seq_num"], "card_id":land_id})
