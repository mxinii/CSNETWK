def format_land_display(card_id, card_data, perm_state):
    card_name = card_data.get("card_name", "")
    tapped_status = "TAPPED" if perm_state.get("tapped") else "UNTAPPED"
    mana_color = LAND_MANA_MAP.get(card_name, "{C}")
    return f"[{mana_color}] {card_id} ({card_name}) - {tapped_status}"

