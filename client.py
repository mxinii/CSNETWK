def log_pdu(direction: str, pdu: dict):
    """direction: 'SEND' (C->S) or 'RECV' (S->C)."""
    if not VERBOSE:
        return
    timestamp = datetime.datetime.now().strftime("%H:%M:%S.%f")[:-3]
    label = "CLIENT SEND -> SERVER" if direction == "SEND" else "CLIENT RECV <- SERVER"
    rendered = json.dumps(pdu, ensure_ascii=False, indent=2)
    with verbose_log_lock:
        print(f"\n[VERBOSE {timestamp}] [{label}]\n{rendered}", flush=True)

