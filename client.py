def receiver():
    """Receive continuously so PONG is processed even during an input prompt."""
    while not stop_event.is_set():
        try:
            pdu = recv_pdu(client_socket)
        except (OSError, ValueError, UnicodeDecodeError, json.JSONDecodeError):
            pdu = None
        if pdu is None:
            incoming_pdus.put(None)
            return
        if pdu.get("type") == "PONG":
            with pong_lock:
                event = pending_pongs.get(pdu.get("seq_num"))
            if event is not None:
                event.set()
            # recv_pdu already prints this PDU in verbose mode. Keep normal
            # gameplay quiet; PONG is connection maintenance, not a game event.
            continue
        incoming_pdus.put(pdu)

def heartbeat():
    """Send PING every 30 seconds and require its matching PONG within 10."""
    seq = 1
    while not stop_event.wait(PING_INTERVAL_SECONDS):
        seq += 1
        pong_received = threading.Event()
        with pong_lock:
            pending_pongs[seq] = pong_received
        try:
            send_pdu(client_socket, {"type": "PING", "seq_num": seq,
                                     "timestamp": int(time.time() * 1000)})
        except OSError:
            stop_event.set()
            incoming_pdus.put(None)
            return
        if not pong_received.wait(PONG_TIMEOUT_SECONDS):
            print(f"[C] No matching PONG within {PONG_TIMEOUT_SECONDS} seconds; disconnecting.")
            stop_event.set()
            try:
                client_socket.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass
            incoming_pdus.put(None)
            return
        with pong_lock:
            pending_pongs.pop(seq, None)

threading.Thread(target=receiver, daemon=True).start()
threading.Thread(target=heartbeat, daemon=True).start()

mulligan_count = 0  # tracks how many times we've mulliganed, used to size cards_to_bottom
latest_state = {}
announced_starting_player = None

# main event loop
while True:
    if pending_reply is not None:
        reply, pending_reply = pending_reply, None
    else:
        reply = incoming_pdus.get()

    if reply is None:
        print("[C] Server disconnected.")
        break

    msg_type = reply.get("type")

    if msg_type == "GAME_STATE_UPDATE":
        state = reply.get("state", {})
        latest_state = state
        phase = state.get("phase")

        print(f"\n=== {state.get('phase')} ===")

        if state.get("phase") == "LOBBY":
            print(f"Players Ready: {state['players_ready']}")
            print(f"Waiting For: {state['waiting_for']}")

        elif state.get("phase") == "MULLIGAN":
            starting_player = state.get("active_player")
            if announced_starting_player != starting_player:
                print(f"\n[GAME] {starting_player} was randomly selected to go first.")
                announced_starting_player = starting_player
            print(f"Turn: {state['turn']}")
            print(f"Active Player: {state['active_player']}")
            print(f"Life Totals: {state['life_totals']}")
            print(f"My Hand: {state['hand']}")
            print(f"Hand Counts: {state['hand_counts']}")
            print(f"Library Counts: {state['library_counts']}")
            print(f"Battlefield: {state['battlefield']}")
            print(f"Graveyard: {state['graveyard']}")
            print(f"Stack: {state['stack']}")

            # Prompt for this player's mulligan decision and send MULLIGAN_CHOICE.
            # seq_num echoes this GAME_STATE_UPDATE's seq_num, per RFC 5.4.
            decision = prompt_until("Keep this hand? (y = keep / n = mulligan): ",
                                    lambda x: choice(x,("y","n"),"mulligan choice"))

            if decision == "y":
                cards_to_bottom = []
                if mulligan_count > 0:
                    print(f"You mulliganed {mulligan_count} time(s); "
                          f"choose {mulligan_count} card(s) to bottom from your hand.")
                    available=list(state["hand"])
                    for i in range(mulligan_count):
                        card = prompt_until(f"  Card {i+1} to bottom: ",
                            lambda x, available=available: nonempty(x,"card ID") if x.strip() in available else (_ for _ in ()).throw(ValueError("card must be a remaining card in your hand")))
                        cards_to_bottom.append(card)
                        available.remove(card)

                send_pdu(client_socket, {
                    "type": "MULLIGAN_CHOICE",
                    "seq_num": reply["seq_num"],
                    "keep": True,
                    "cards_to_bottom": cards_to_bottom
                })
            else:
                mulligan_count += 1
                send_pdu(client_socket, {
                    "type": "MULLIGAN_CHOICE",
                    "seq_num": reply["seq_num"],
                    "keep": False,
                    "cards_to_bottom": []
                })

        elif state.get("phase") == "IN_GAME":
            step = state.get("step")
            hand = state.get("hand", [])
            print(f"Turn: {state.get('turn')} | Active Player: {state.get('active_player')} | Step: {step}")
            print(f"Life: {state.get('life_totals')} | Hand: {hand}")

            # Hand Size Enforcement during Cleanup Step (RFC 7.8)
            if step == "CLEANUP" and state.get("active_player") == player_id and len(hand) > 7:
                excess = len(hand) - 7
                print(f"\n[CLEANUP] Your hand size exceeds 7! You must discard {excess} card(s).")
                discard_list = []
                available=list(hand)
                for i in range(excess):
                    card = prompt_until(f"  Card {i+1} ID to discard: ",
                        lambda x, available=available: nonempty(x,"card ID") if x.strip() in available else (_ for _ in ()).throw(ValueError("card must be a remaining card in your hand")))
                    discard_list.append(card)
                    available.remove(card)

                send_pdu(client_socket, {
                    "type": "DISCARD",
                    "seq_num": reply["seq_num"],  # Echo last GAME_STATE_UPDATE seq_num
                    "card_ids": discard_list
                })

    elif msg_type == "PRIORITY_GRANT":
        print(f"\n[PRIORITY] You have priority (seq_num: {reply.get('seq_num')}).")
        # New servers include the step in PRIORITY_GRANT.  The state fallback
        # keeps the client compatible with an older server during upgrades.
        step = reply.get("step") or latest_state.get("step")
        active_player = latest_state.get("active_player")
        print(f"Current turn: {active_player} | Step: {step}")
        show_cards("Your hand", latest_state.get("hand", []))
        pool_text, untapped_lands = visible_mana(latest_state, player_id)
